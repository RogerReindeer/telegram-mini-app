begin;

set local lock_timeout = '5s';
set local statement_timeout = '60s';

-- A legacy trigger and the current trigger were both incrementing the same
-- analytics profile. Keep the current SECURITY INVOKER implementation only.
drop trigger if exists analytics_events_touch_user_profile on public.analytics_events;
drop function if exists public.analytics_touch_user_profile();

alter function public.update_analytics_user_profile() security invoker;
alter function public.update_analytics_user_profile() set search_path = '';
revoke execute on function public.update_analytics_user_profile()
  from public, anon, authenticated;
grant execute on function public.update_analytics_user_profile()
  to service_role;

-- analytics_user_profiles is derived state. Rebuild every profile from the
-- immutable event rows so historical double increments are repaired as well.
with event_rollup as (
  select
    telegram_user_id,
    min(created_at) as first_seen_at,
    max(created_at) as last_seen_at,
    coalesce(
      (array_agg(nullif(source, '') order by created_at, event_id))[1],
      'direct'
    ) as first_source,
    coalesce(
      (array_agg(nullif(source, '') order by created_at desc, event_id desc))[1],
      'direct'
    ) as current_source,
    count(*)::bigint as total_events
  from public.analytics_events
  group by telegram_user_id
)
insert into public.analytics_user_profiles (
  telegram_user_id, first_seen_at, last_seen_at, first_source,
  current_source, total_events, updated_at
)
select
  telegram_user_id, first_seen_at, last_seen_at, first_source,
  current_source, total_events, now()
from event_rollup
on conflict (telegram_user_id) do update set
  first_seen_at = excluded.first_seen_at,
  last_seen_at = excluded.last_seen_at,
  first_source = excluded.first_source,
  current_source = excluded.current_source,
  total_events = excluded.total_events,
  updated_at = now();

delete from public.analytics_user_profiles p
where not exists (
  select 1
  from public.analytics_events e
  where e.telegram_user_id = p.telegram_user_id
);

-- Older installations contain this reporting view. Keep it available only to
-- the backend and make it respect the caller's RLS context.
do $$
begin
  if to_regclass('public.analytics_daily') is not null then
    alter view public.analytics_daily set (security_invoker = true);
    revoke all on table public.analytics_daily from public, anon, authenticated;
    grant select on table public.analytics_daily to service_role;
  end if;
end $$;

-- subscription_plans is a legacy, currently unused table. Preserve it rather
-- than deleting data, but remove direct Data API access.
do $$
begin
  if to_regclass('public.subscription_plans') is not null then
    alter table public.subscription_plans enable row level security;
    revoke all on table public.subscription_plans from public, anon, authenticated;
    grant all on table public.subscription_plans to service_role;
  end if;
end $$;

-- Two legacy updated_at triggers duplicate the canonical zefirki trigger.
drop trigger if exists set_user_novel_state_updated_at on public.user_novel_state;
drop trigger if exists set_user_chapter_progress_updated_at on public.user_chapter_progress;
drop function if exists public.set_current_updated_at();

do $$
begin
  if to_regprocedure('public.zefirki_touch_updated_at()') is not null then
    alter function public.zefirki_touch_updated_at() security invoker;
    alter function public.zefirki_touch_updated_at() set search_path = '';
    revoke execute on function public.zefirki_touch_updated_at()
      from public, anon, authenticated;
    grant execute on function public.zefirki_touch_updated_at()
      to service_role;
  end if;
end $$;

-- Add stable row identities while the legacy commerce tables are still empty.
alter table public.user_subscriptions
  add column if not exists subscription_id bigint generated by default as identity;
alter table public.user_entitlements
  add column if not exists entitlement_id bigint generated by default as identity;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.user_subscriptions'::regclass and contype = 'p'
  ) then
    alter table public.user_subscriptions
      add constraint user_subscriptions_pkey primary key (subscription_id);
  end if;

  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.user_entitlements'::regclass and contype = 'p'
  ) then
    alter table public.user_entitlements
      add constraint user_entitlements_pkey primary key (entitlement_id);
  end if;
end $$;

-- PostgreSQL does not automatically index referencing columns. These indexes
-- keep joins and ON DELETE actions predictable as commerce data grows.
create index if not exists boosty_orders_bundle_idx
  on public.boosty_orders(boosty_bundle_key);
create index if not exists boosty_products_novel_idx
  on public.boosty_products(novel_id);
create index if not exists reader_entitlements_chapter_idx
  on public.reader_commerce_entitlements(chapter_id);
create index if not exists reader_entitlements_novel_idx
  on public.reader_commerce_entitlements(novel_id);
create index if not exists reader_entitlements_purchase_idx
  on public.reader_commerce_entitlements(purchase_id);
create index if not exists reader_store_products_chapter_idx
  on public.reader_store_products(chapter_id);
create index if not exists reader_store_products_novel_idx
  on public.reader_store_products(novel_id);
create index if not exists reader_store_purchases_product_idx
  on public.reader_store_purchases(product_code);
create index if not exists user_chapter_progress_chapter_idx
  on public.user_chapter_progress(chapter_id);
create index if not exists user_chapter_progress_novel_fk_idx
  on public.user_chapter_progress(novel_id);
create index if not exists user_entitlements_novel_fk_idx
  on public.user_entitlements(novel_id);
create index if not exists user_novel_state_last_chapter_idx
  on public.user_novel_state(last_chapter_id);
create index if not exists user_novel_state_novel_fk_idx
  on public.user_novel_state(novel_id);

-- Remove only indexes proven byte-for-byte equivalent to retained indexes.
drop index if exists public.user_chapter_progress_last_idx;
drop index if exists public.user_novel_state_user_novel_uidx;

commit;
notify pgrst, 'reload schema';
